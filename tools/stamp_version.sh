#!/bin/bash
# Writes scripts/core/build_stamp.gd: the short git commit (with "-dirty" when
# tracked files have changes, staged or not; untracked files don't count) and
# the most recent git tag (empty when there is none yet). BuildInfo reads it.
# The file is never committed and exists only while a build is made:
# tools/export.sh removes it again, CI throws the checkout away.
#
# Fails (and writes nothing) when git can't say: a wrong stamp is worse than none.
set -euo pipefail
cd "$(dirname "$0")/.."

out=scripts/core/build_stamp.gd
commit=$(git rev-parse --short HEAD)
changed=0
git diff HEAD --quiet || changed=$?
if [ "$changed" -gt 1 ]; then
	echo "stamp_version: git diff failed" >&2
	exit 1
fi
[ "$changed" -eq 0 ] || commit="$commit-dirty"
tag=$(git describe --tags --abbrev=0 2>/dev/null || true)

# The values go into a GDScript string: nothing odd allowed.
for v in "$commit" "$tag"; do
	if [[ ! "$v" =~ ^[A-Za-z0-9._+-]*$ ]]; then
		echo "stamp_version: unexpected characters in '$v'" >&2
		exit 1
	fi
done

tmp=$(mktemp "$out.XXXXXX")
cat > "$tmp" <<STAMP
# Generated by tools/stamp_version.sh while a build is exported. Never committed.
extends RefCounted

const COMMIT := "$commit"
const TAG := "$tag"
STAMP
mv "$tmp" "$out"
echo "stamped: commit $commit, tag ${tag:-none}"
